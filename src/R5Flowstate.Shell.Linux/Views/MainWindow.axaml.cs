    /// <summary>
    /// One pane's find bar. Windows holds the pane's <c>RichTextBox</c> and its
    /// WPF match ranges here; the port holds the pane control and leaves the
    /// matches in the view model (they are line/offset pairs, and the suite can
    /// read them back). Windows identifies a bar's pane through each control's
    /// <c>Tag</c>; so does this one — the tags say "Server"/"Client" rather than
    /// carrying the control, because a XAML <c>Tag</c> cannot name a sibling
    /// control here.
    /// </summary>
    sealed class ConsoleFindBar
    {
        public LaunchRole Role;
        public ConsolePane Pane = null!;
        public Control Bar = null!;
        public TextBox Input = null!;
        public TextBlock Counter = null!;
        public CheckBox CaseToggle = null!;
        public bool Open;

        /// <summary>
        /// Where the player is, as a line, so a rebuild caused by arriving output
        /// keeps them where they were instead of jumping to the oldest match.
        ///
        /// Following the tail wins over the current match, and has to: a
        /// following pane is looking at the newest lines, and its current match
        /// is by definition an older one — anchoring on it would pin the find to
        /// the match it first landed on while the log runs away underneath. Only
        /// a player who has scrolled away is anchored where they are standing.
        /// </summary>
        internal int Anchor(MainViewModel vm)
        {
            if (Pane.Follow)
                return MainViewModel.ConsoleFindTailAnchor;

            var i = vm.FindCurrent(Role);
            var matches = vm.FindMatches(Role);
            return i >= 0 && i < matches.Count ? matches[i].Line : 0;
        }
    }

    readonly List<ConsoleFindBar> _consoleFind = new();
    ConsoleFindBar? _findTarget;
    ConsoleFindBar? _findPendingQuery;
    DispatcherTimer? _findDebounce;
    int _findTick;

    /// <summary>Windows' InitConsoleFind: one bar per pane, the debounce timer,
    /// and the same control wiring (focus in either the pane or its command box
    /// makes that pane the find target).</summary>
    void InitConsoleFind()
    {
        if (_consoleFind.Count > 0)
            return;

        AddConsoleFindBar(LaunchRole.Dedicated, TxtConsoleServer, BarFindServer,
            TxtFindServer, TxtFindServerCount, ChkFindServerCase, TxtConsoleServerCmd);
        AddConsoleFindBar(LaunchRole.Client, TxtConsoleClient, BarFindClient,
            TxtFindClient, TxtFindClientCount, ChkFindClientCase, TxtConsoleClientCmd);
        _findTarget = _consoleFind.FirstOrDefault();

        _findDebounce = new DispatcherTimer(DispatcherPriority.Background)
        {
            Interval = TimeSpan.FromMilliseconds(150),
        };
        _findDebounce.Tick += (_, _) =>
        {
            _findDebounce!.Stop();
            var bar = _findPendingQuery;
            _findPendingQuery = null;
            if (bar is not null)
                RebuildConsoleFind(bar, jump: true);
        };
    }

    void AddConsoleFindBar(LaunchRole role, ConsolePane? pane, Control? bar,
        TextBox? input, TextBlock? counter, CheckBox? caseToggle, TextBox? cmd)
    {
        if (pane is null || bar is null || input is null || counter is null || caseToggle is null)
            return;

        var find = new ConsoleFindBar
        {
            Role = role,
            Pane = pane,
            Bar = bar,
            Input = input,
            Counter = counter,
            CaseToggle = caseToggle,
        };
        _consoleFind.Add(find);

        pane.GotFocus += (_, _) => _findTarget = find;

        // A press anywhere in the pane aims the find bar at it. Tunneled, not
        // bubbled: the pane is full of text controls that mark a press handled,
        // and the player's press is still a press on the pane.
        pane.AddHandler(InputElement.PointerPressedEvent,
            (_, _) => _findTarget = find, RoutingStrategies.Tunnel);
        pane.AddHandler(InputElement.PointerPressedEvent,
            (_, _) => _findTarget = find, RoutingStrategies.Bubble, handledEventsToo: true);
        input.GotFocus += (_, _) => _findTarget = find;
        if (cmd is not null)
            cmd.GotFocus += (_, _) => _findTarget = find;
    }

    /// <summary>Every find control carries its own pane's role in Tag.</summary>
    ConsoleFindBar? FindBarOf(object? sender) =>
        sender is Control { Tag: string tag }
            ? _consoleFind.FirstOrDefault(b => b.Role == ParseTag(tag))
            : null;

    /// <summary>
    /// The tags say "Server"/"Client" — the words on the tabs, matching the
    /// console command boxes — while the roles are Dedicated/Client. The server
    /// pane is the dedicated one.
    /// </summary>
    static LaunchRole ParseTag(string tag) =>
        tag == "Client" ? LaunchRole.Client : LaunchRole.Dedicated;

    ConsoleFindBar? ActiveConsoleFind() =>
        _findTarget is { Open: true } ? _findTarget
        : _consoleFind.FirstOrDefault(b => b.Open);

    /// <summary>True while a pane's bar is open. Windows' ConsoleFindHolds asks
    /// the same question where it decides what follows what: a pane with an open
    /// bar is following a match, so it must not be dragged back to the tail by
    /// the next batch — and a match the fresh lines have just moved has to be
    /// repainted, which is what <see cref="ConsoleFindTick"/> is for.</summary>
    bool ConsoleFindHolds(ConsolePane pane) =>
        _consoleFind.Any(b => b.Open && ReferenceEquals(b.Pane, pane));

    void OpenConsoleFind(ConsoleFindBar? bar)
    {
        bar ??= _findTarget ?? _consoleFind.FirstOrDefault();
        if (bar is null)
            return;

        _findTarget = bar;
        bar.Open = true;
        bar.Bar.IsVisible = true;

        // A find bar needs the console reading, because its count follows the
        // pane's revision (Windows starts the same timer here).
        StartConsoleTimer();

        var seed = bar.Pane.SelectedText;
        if (seed.Length > 0)
            bar.Input.Text = seed;

        bar.Input.Focus();
        bar.Input.SelectAll();
        RebuildConsoleFind(bar, jump: true);
    }

    void CloseConsoleFind(ConsoleFindBar bar)
    {
        // Closing forgets the search as well as the paint: nothing should be
        // highlighted after Escape, and the next Ctrl+F starts clean. This goes
        // through a rebuild with an empty query rather than ResetFind, because
        // ResetFind is the pane's own reset (a cleared pane, whose player keeps
        // wanting what they typed) and this one is the player's.
        Vm.RebuildFind(bar.Role, "", false, 0);
        bar.Pane.ClearFindMatch();
        bar.Open = false;
        bar.Bar.IsVisible = false;
        bar.Counter.Text = "";
        bar.Input.Text = "";
        bar.Pane.Focus();
    }

    /// <summary>
    /// Windows' ConsoleFindTick: every fourth tick of the console timer, an open
    /// bar whose pane has taken lines re-finds — four ticks is about a second of
    /// streaming output, which is how long a count can be stale before a player
    /// notices. Internal because the suite has no message loop to tick the timer
    /// for it, and calls this where a real window would.
    ///
    /// A rebuild here follows the pane: while the pane is following its tail the
    /// current match is the newest one, so the highlight goes with it; a player
    /// who has scrolled away keeps the highlight and only the count moves.
    /// </summary>
    internal void ConsoleFindTick()
    {
        Console.Error.WriteLine($"[find] tick n={_findTick + 1} stack={Environment.StackTrace.Split('\n')[2].Trim()}");
        if (++_findTick % 4 != 0)
            return;

        foreach (var bar in _consoleFind)
        {
            if (bar.Open && Vm.FindQuery(bar.Role).Length > 0)
                RebuildConsoleFind(bar, jump: bar.Pane.Follow);
        }
    }

    void RebuildConsoleFind(ConsoleFindBar bar, bool jump)
    {
        var view = Vm.RebuildFind(bar.Role, bar.Input.Text ?? "",
            bar.CaseToggle.IsChecked == true, bar.Anchor(Vm));
        ApplyFindView(bar, view, jump);
    }

    void StepConsoleFind(ConsoleFindBar bar, int delta)
    {
        if (!bar.Open)
            return;

        var view = Vm.StepFind(bar.Role, delta, bar.Anchor(Vm));
        ApplyFindView(bar, view, jump: true);
    }

    void ApplyFindView(ConsoleFindBar bar, ConsoleFindView view, bool jump)
    {
        bar.Counter.Text = view.Counter;
        if (jump && view.HasMatch)
            bar.Pane.ShowFindMatch(view.Match);
        else if (!view.HasMatch)
            bar.Pane.ClearFindMatch();
    }

