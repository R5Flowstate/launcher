    private int _eulaVersionCurrent;
    private bool _eulaDialogOpen;

    /// <summary>Same endpoint the Windows build ships with (ProductConstants).</summary>
    private static string CurrentMasterServerUrl() => NoticeClient.DefaultMasterServerUrl;

    /// <summary>Windows parity: MainWindow.ServersUnlocked.</summary>
    private bool ServersUnlocked() =>
        MainViewModel.ServersUnlockedFor(Vm.EulaVersionAccepted, _eulaVersionCurrent);

    /// <summary>
    /// Shows the agreement before anything from the master server is listed.
    /// Returns true when the player has accepted the current notice version.
    /// </summary>
    private async System.Threading.Tasks.Task<bool> EnsureEulaAcceptedAsync()
    {
        if (_eulaDialogOpen)
            return false;

        // Already accepted at this session's known-current version: no round
        // trip. A server-side bump is picked up on the next launcher start.
        if (_eulaVersionCurrent > 0 && Vm.EulaVersionAccepted >= _eulaVersionCurrent)
            return true;

        var fetched = await NoticeClient.GetEulaAsync(CurrentMasterServerUrl(), Vm.EulaUiLanguage());
        if (!fetched.Success)
        {
            Vm.BrowserStatus = fetched.Error ?? Loc.Get("status_eula_failed");
            Vm.SimpleStatus = Loc.Get("status_eula_failed_retry");
            Vm.AppendLog("Legal notice fetch failed: " + (fetched.Error ?? "unknown error"));
            return false;
        }

        _eulaVersionCurrent = fetched.Version > 0 ? fetched.Version : 1;
        if (Vm.EulaVersionAccepted >= _eulaVersionCurrent)
            return true;

        _eulaDialogOpen = true;
        try
        {
            var dlg = new EulaWindow(this, CurrentMasterServerUrl(), requireAccept: true,
                prefetched: fetched, vm: Vm);
            var ok = await dlg.ShowDialog<bool>(this);
            if (!ok || !dlg.Accepted)
            {
                Vm.BrowserStatus = Loc.Get("status_eula_servers");
                Vm.SimpleStatus = Loc.Get("status_eula_servers");
                Vm.AppendLog("Legal notice declined — the Servers tab stays locked.");
                return false;
            }
            Vm.SaveEulaAccepted(dlg.AcceptedVersion);
            _eulaVersionCurrent = dlg.AcceptedVersion;
            Vm.AppendLog($"Legal notice v{dlg.AcceptedVersion} accepted ({fetched.Lang}).");
            return true;
        }
        finally
        {
            _eulaDialogOpen = false;
        }
    }

