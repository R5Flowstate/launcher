    /// <summary>
    /// A typed-in size, committed when the box loses focus (upstream's
    /// OnClientResolutionLostFocus). Reads the boxes rather than the view model,
    /// because the two-way binding is what carries a <em>parseable</em> number and
    /// nothing carries an unparseable one: "1e9" never reaches ClientWidth, so the
    /// box has to be told what the value actually is afterwards — which is what the
    /// write-back below does, for both good and refused input.
    /// </summary>
    private void OnClientResolutionLostFocus(object? sender, RoutedEventArgs e)
    {
        var w = ReadBox(TxtClientWidth, Vm.ClientWidth);
        var h = ReadBox(TxtClientHeight, Vm.ClientHeight);
        // Only when something actually changed. Tabbing from the width box to the
        // height box is a LostFocus too, and committing an unchanged pair would write
        // settings.json and add a log line for every focus change.
        if (w != Vm.ClientWidth || h != Vm.ClientHeight)
            Vm.SetResolution(w, h);

        // Both boxes, whichever one was left: the pair is what launches, so a size
        // that was refused has to snap back in both.
        TxtClientWidth.Text = Vm.ClientWidth.ToString();
        TxtClientHeight.Text = Vm.ClientHeight.ToString();
        // The Servers tab's twin boxes are bound to the same two properties, so they
        // follow on their own; the write-back above is only for the pair on screen.
    }

    static int ReadBox(TextBox box, int fallback)
        => int.TryParse(box.Text?.Trim(), out var value) ? value : fallback;

