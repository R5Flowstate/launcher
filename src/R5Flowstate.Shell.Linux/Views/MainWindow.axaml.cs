    /// <summary>
    /// Windows' OnResolutionPresetClick: build the menu from what the session lists
    /// and open it. Built per click rather than cached, because the modes a display
    /// offers can change while the launcher is open — a monitor plugged in, a KDE
    /// resolution change — and a stale menu is one that offers a size that is no
    /// longer there. The build reads an enumeration that is already cached, so it
    /// costs nothing per click.
    ///
    /// Three sections, upstream's order: the window modes as a radio group, a
    /// separator, then "Game default" and one submenu per aspect group. Avalonia's
    /// <see cref="MenuItemToggleType.Radio"/> is what keeps two modes from being
    /// ticked at once — Windows hand-rolls that with SyncWindowModeChecks because WPF
    /// has no radio menu item.
    /// </summary>
    private void OnResolutionPresetClick(object? sender, RoutedEventArgs e)
    {
        if (sender is not Button target)
            return;

        var menu = new ContextMenu { Placement = PlacementMode.Top };
        menu.Classes.Add(ResMenuClass);

        foreach (var mode in DisplayModes.WindowModes)
        {
            var item = new MenuItem
            {
                Header = Loc.Get(DisplayModes.LocKey(mode)),
                Tag = mode,
                ToggleType = MenuItemToggleType.Radio,
                GroupName = "r5f-window-mode",
                IsChecked = mode == Vm.ClientWindowMode,
            };
            item.Classes.Add(ResMenuClass);
            item.Click += OnWindowModePicked;
            menu.Items.Add(item);
        }

        var separator = new Separator();
        separator.Classes.Add(ResMenuClass);
        menu.Items.Add(separator);

        // The one entry Windows has no equivalent of: this port treats 0x0 as "no
        // override", which is the only way back to the game's own choice once a size
        // has been picked.
        var gameDefault = new MenuItem
        {
            Header = Loc.Get("resolution_game_default"),
            Tag = new DisplayModes.DisplayMode(0, 0),
        };
        gameDefault.Classes.Add(ResMenuClass);
        gameDefault.Click += OnResolutionPresetPicked;
        menu.Items.Add(gameDefault);

        foreach (var group in DisplayModes.Groups())
        {
            var header = new MenuItem { Header = group.Caption };
            header.Classes.Add(ResMenuClass);

            foreach (var preset in group.Modes)
            {
                var item = new MenuItem
                {
                    Header = DisplayModes.Label(preset),
                    Tag = preset,
                };
                item.Classes.Add(ResMenuClass);
                item.Click += OnResolutionPresetPicked;
                header.Items.Add(item);
            }

            menu.Items.Add(header);
        }

        // The class has to be on every item, not just on the menu: a MenuItem built
        // here is not a child of the ContextMenu, and the submenu's items are not
        // children of the group header. The theme's selectors are scoped by it
        // (ContextMenu.resmenu / MenuItem.resmenu / Separator.resmenu), which is why
        // upstream's per-group ItemContainerStyle restatement has no equivalent here.
        target.ContextMenu = menu;
        menu.Open(target);
    }

