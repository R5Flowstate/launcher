    /// <summary>The browser's own refresh cadence, same 12 s as the Windows
    /// launcher. Owned by the window because visibility is a window fact: the
    /// timer runs only while the Servers tab is the visible one.</summary>
    private Avalonia.Threading.DispatcherTimer? _browserTimer;

    private void StartBrowserPoll()
    {
        // A tab with no install behind it has nothing to list (the tab itself is
        // disabled in that state, so this is the belt to that braces).
        if (!ServersUnlocked() || !InstallPresence.GamePresent(Vm.InstallPath))
        {
            StopBrowserPoll();
            return;
        }

        if (_browserTimer is null)
        {
            _browserTimer = new Avalonia.Threading.DispatcherTimer
            {
                Interval = TimeSpan.FromSeconds(12),
            };
            _browserTimer.Tick += OnBrowserTick;
        }
        if (!_browserTimer.IsEnabled)
            _browserTimer.Start();
    }

    private void StopBrowserPoll() => _browserTimer?.Stop();

    private async void OnBrowserTick(object? sender, EventArgs e)
    {
        if (!ServersUnlocked())
        {
            StopBrowserPoll();
            return;
        }
        // Quiet: the same fetch the refresh button makes, without repainting the
        // status line to "Refreshing…" every 12 s.
        await Vm.PollServersAsync();
    }

