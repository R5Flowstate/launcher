    /// <summary>
    /// The console's two panes, and the timer that feeds them. Lines arrive on
    /// the tap's reader threads, so they queue in the view model and land here in
    /// batches — Windows' own arrangement, for the same reason: appending a line
    /// at a time relayouts the pane thousands of times over a boot.
    /// </summary>
    void AttachConsole()
    {
        Vm.ConsoleLineQueued += StartConsoleTimer;

        // Windows' two-second _procWatch, which is where its host heartbeat
        // ticks from (MainWindow.xaml.cs:498-504). It cannot ride the console
        // drain timer above: that one stops whenever nothing is printing, and a
        // server that has stopped printing is exactly the case the watchdog
        // exists for. The view model enforces the ten-second spacing, so this
        // interval only decides how promptly a due ping goes out.
        _procWatch = new DispatcherTimer(DispatcherPriority.Background)
        {
            Interval = TimeSpan.FromSeconds(2),
        };
        _procWatch.Tick += (_, _) => Vm.TickHostHeartbeat();
        _procWatch.Start();

        // A console appearing means a launch happened, which is where Windows
        // brings the tab forward; and the server pane's own rule (a browser join
        // has no dedi of ours) is read through the view model, so it is
        // re-applied whenever that answer can have changed.
        Vm.ConsoleAttached += _ => MaybeOpenConsoleForLaunch();
        Vm.PropertyChanged += (_, e) =>
        {
            if (e.PropertyName == nameof(MainViewModel.ConsoleServerPaneOpen))
                ApplyConsoleView();
            else if (e.PropertyName is nameof(MainViewModel.HostSteeringReady)
                     or nameof(MainViewModel.ChangeMapBusy))
                RefreshConsoleChrome();
        };

        Vm.ConsoleReset += role =>
        {
            var pane = PaneFor(role);
            pane.Follow = true;
            pane.ClearFindMatch();

            // A cleared pane has no matches, so an open bar's count goes back to
            // nothing rather than holding a number about lines that are gone
            // (Windows' ResetConsoleFind does the same from the clear path).
            foreach (var bar in _consoleFind)
            {
                if (bar.Role == role && bar.Open)
                    bar.Counter.Text = "";
            }
        };
        Vm.ConsoleNoted += (role, text) =>
        {
            // The pane's own voice is worth seeing even when the player is on
            // another tab, so a note brings the console forward only if the
            // console is already the tab in front of them.
            if (PanelSimpleConsole.IsVisible)
                PaneFor(role).PinToEnd();
            else
                Vm.AppendLog(text);
        };

        InitConsoleFind();

        _consoleTimer = new DispatcherTimer(DispatcherPriority.Background)
        {
            Interval = TimeSpan.FromMilliseconds(250),
        };
        _consoleTimer.Tick += (_, _) =>
        {
            var painted = 0;
            foreach (var role in new[] { LaunchRole.Dedicated, LaunchRole.Client })
            {
                var pane = PaneFor(role);
                painted += Vm.DrainConsole(role);

                // A pane whose find bar is open is following a match, not the
                // tail — pinning it would scroll the player off what they are
                // reading. Its counter is kept honest instead.
                if (!ConsoleFindHolds(pane) && pane.Follow && painted > 0)
                    pane.PinToEnd();
            }

            ConsoleFindTick();

            if (!Vm.HasPendingConsole)
            {
                _consoleTimer.Stop();
                // A line queued between the drain and the stop saw the timer
                // still enabled and did not restart it.
                if (Vm.HasPendingConsole)
                    _consoleTimer.Start();
            }
        };
    }

