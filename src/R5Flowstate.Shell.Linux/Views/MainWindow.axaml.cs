    /// <summary>Enter sends, Up/Down walk the command history — the same keys
    /// the Windows console box handles, with the history kept in the settings
    /// file so it survives a restart.</summary>
    private void OnConsoleServerCmdKeyDown(object? sender, KeyEventArgs e) =>
        HandleConsoleCmdKey(e, LaunchRole.Dedicated);

    private void OnConsoleClientCmdKeyDown(object? sender, KeyEventArgs e) =>
        HandleConsoleCmdKey(e, LaunchRole.Client);

    void HandleConsoleCmdKey(KeyEventArgs e, LaunchRole role)
    {
        var box = role == LaunchRole.Dedicated ? TxtConsoleServerCmd : TxtConsoleClientCmd;
        var history = Vm.HistoryFor(role);
        var nav = role == LaunchRole.Dedicated ? _historyNavServer : _historyNavClient;

        switch (e.Key)
        {
            case Key.Enter:
                var line = (box.Text ?? "").Trim();
                if (role == LaunchRole.Dedicated)
                    Vm.SubmitServerCommand(line);
                else
                    Vm.SubmitClientCommand(line);
                nav.Index = -1;
                nav.Draft = "";
                box.Text = "";
                e.Handled = true;
                break;

            case Key.Up:
                if (history.Count == 0)
                    return;
                if (nav.Index < 0)
                {
                    nav.Draft = box.Text ?? "";
                    nav.Index = history.Count - 1;
                }
                else if (nav.Index > 0)
                {
                    nav.Index--;
                }
                box.Text = history[nav.Index];
                box.CaretIndex = box.Text.Length;
                e.Handled = true;
                break;

            case Key.Down:
                if (nav.Index < 0)
                    return;
                nav.Index++;
                if (nav.Index >= history.Count)
                {
                    nav.Index = -1;
                    box.Text = nav.Draft;
                }
                else
                {
                    box.Text = history[nav.Index];
                }
                box.CaretIndex = box.Text.Length;
                e.Handled = true;
                break;
        }
    }

