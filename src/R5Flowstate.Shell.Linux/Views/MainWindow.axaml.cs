    private void SetSimpleTab(Button? tab, Control panel)
    {
        foreach (var b in new[]
                 {
                     BtnTabLocal, BtnTabServers, BtnTabLeaderboards, BtnTabConsole, BtnTabMods,
                     BtnTabBlog, BtnTabNotes, BtnTabCredits,
                 })
        {
            b.Classes.Remove("on");
        }
        foreach (var p in new[]
                 {
                     PanelSimpleLocal, PanelSimpleServers, PanelSimpleLeaderboards, PanelSimpleConsole,
                     PanelSimpleMods, PanelSimpleBlog, PanelSimpleNotes, PanelSimpleCredits,
                     (Control)PanelSimpleSettings,
                 })
        {
            p.IsVisible = false;
        }
        tab?.Classes.Add("on");
        panel.IsVisible = true;

        // The browser's line belongs to the Servers tab (Windows toggles the same
        // TextBlock in ApplySimpleTab), and the 12 s poll only runs while that tab
        // is the visible one — a hidden tab has no business on the network.
        var servers = ReferenceEquals(panel, PanelSimpleServers);
        TxtBrowserStatus.IsVisible = servers;
        if (servers)
            StartBrowserPoll();
        else
            StopBrowserPoll();

        // Same rule for the leaderboards: the 30 s board poll and the 15 s
        // activity poll only run while that tab is the visible one. (Windows
        // leaves the activity timer up on every tab, but its only consumer is a
        // line inside this panel, so stopping it off-tab costs nothing visible
        // and saves a request every 15 s.)
        if (ReferenceEquals(panel, PanelSimpleLeaderboards))
            StartLeaderboardPoll();
        else
            StopLeaderboardPoll();

        // Windows parity (ApplySimpleTab): the header Refresh button belongs to
        // the three networked tabs and says what it will refresh, and it is the
        // tab's own refresh rather than always the server list.
        var blog = ReferenceEquals(panel, PanelSimpleBlog);
        BtnBrowserRefresh.IsVisible = servers || ReferenceEquals(panel, PanelSimpleLeaderboards) || blog;
        BtnBrowserRefresh.SetValue(ToolTip.TipProperty, Loc.Get(
            ReferenceEquals(panel, PanelSimpleLeaderboards) ? "tip_refresh_lb"
            : blog ? "tip_refresh_blog"
            : "tip_refresh_servers"));

        // The blog's own two concerns: the unread dot is stamped while the tab
        // is up (SyncBlogTab in Windows), and the list comes back scrolled to
        // the top whenever the tab is entered.
        Vm.SetBlogTabShown(blog);
        if (blog && PanelBlogList.IsVisible)
            ScrollBlogList.ScrollToHome();

        // The console's chrome follows the tab: Stop is only offered while the
        // console is the pane in front of the player (RefreshConsoleChrome).
        if (DataContext is not null)
            RefreshConsoleChrome();
    }

