    private void OnConsoleFindTextChanged(object? sender, TextChangedEventArgs e)
    {
        if (FindBarOf(sender) is not { } bar)
            return;

        // Closing a bar empties its box, and that is not a query.
        if (!bar.Open)
        {
            if (ReferenceEquals(_findPendingQuery, bar))
            {
                _findPendingQuery = null;
                _findDebounce?.Stop();
            }
            return;
        }

        // A query typed in one bar flushes the other: the debounce holds one
        // pending query, exactly as Windows' does.
        if (_findPendingQuery is not null && !ReferenceEquals(_findPendingQuery, bar))
            RebuildConsoleFind(_findPendingQuery, jump: true);

        _findPendingQuery = bar;
        _findDebounce?.Stop();
        _findDebounce?.Start();
    }

    private void OnConsoleFindKeyDown(object? sender, KeyEventArgs e)
    {
        if (FindBarOf(sender) is not { } bar)
            return;

        switch (e.Key)
        {
            case Key.Enter:
            {
                // Enter on a query the debounce has not run yet searches first —
                // the rebuild already lands on the match nearest the anchor, so
                // stepping here as well would skip it. Enter again steps.
                var pending = ReferenceEquals(_findPendingQuery, bar);
                FlushConsoleFindQuery(bar);
                if (!pending)
                    StepConsoleFind(bar, e.KeyModifiers.HasFlag(KeyModifiers.Shift) ? -1 : 1);
                e.Handled = true;
                break;
            }

            case Key.Escape:
                CloseConsoleFind(bar);
                e.Handled = true;
                break;
        }
    }

    /// <summary>
    /// Run the query the debounce has not run yet, and show its match: this is
    /// what Enter does, so it paints — a player who pressed the key is asking to
    /// be taken there, unlike the debounce, which only counts.
    /// </summary>
    void FlushConsoleFindQuery(ConsoleFindBar bar)
    {
        if (!ReferenceEquals(_findPendingQuery, bar))
            return;
        _findPendingQuery = null;
        _findDebounce?.Stop();
        RebuildConsoleFind(bar, jump: true);
    }

