    private void AttachInstallGate()
    {
        // Mirrors the Windows launcher's ShowSimpleSetupLayout: the setup card
        // replaces the play panel *and its action bar* while the install is
        // missing, the tab is relabelled once the install exists, and the server
        // browser stays locked until then.
        //
        // "The install is missing" is asked through InstallPresence rather than
        // LooksLikeInstall, because a root with the platform lane and no game
        // satisfies Windows' marker rule (the platform ships its own client.dll)
        // and would hide the one card that can install the game. See
        // InstallPresence.
        var setup = !InstallPresence.GamePresent(Vm.InstallPath);
        PanelSimpleSetup.IsVisible = setup;
        PanelSimplePlay.IsVisible = !setup;
        PanelSimplePlayOptions.IsVisible = !setup;
        // The bar carries PLAY / CHANGE MAP, neither of which is meaningful
        // before there is an install — the setup card owns the CTA.
        BarSimplePlay.IsVisible = !setup;
        BtnTabLocal.Content = Loc.Get(setup ? "tab_install" : "tab_play_local");
        BtnTabServers.IsEnabled = !setup;
        BtnTabServers.Opacity = setup ? 0.4 : 1;
        BtnTabServers.SetValue(ToolTip.TipProperty, Loc.Get(
            setup ? "tip_servers_locked"
                  : ServersUnlocked() ? "tip_browse_servers" : "status_eula_servers"));
        // The size line must resolve to a real state (measured, or "size
        // unknown") rather than sitting on the checking placeholder.
        _ = Vm.RefreshInstallSizeAsync();
        // And the install's playlists are read here too, because whether they
        // exist is part of what "the install is present" means: Windows reloads
        // its catalog at exactly these points (startup and an install change).
        _ = Vm.ReloadCatalogAsync();
        // The Local tab is the one that opens, and it owns no browser line — nor
        // the header Refresh button, which belongs to Servers/Leaderboards/Blog.
        TxtBrowserStatus.IsVisible = false;
        BtnBrowserRefresh.IsVisible = false;
    }

